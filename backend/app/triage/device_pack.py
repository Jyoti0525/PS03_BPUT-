"""The rule pack as one JSON file for the device (frontend/src/lib/triage/rulepack.json).

An offline kiosk runs the same rules, word lists and negation as the server (frontend/src/lib/triage/engine.ts), so a
danger sign is caught while the network is down. Everything here is read from the server's own tables, never copied by
hand; tests/test_device_rules.py fails when the JSON is stale and runs both engines on the same patients.

Build from backend/:  python scripts/build_rulepack.py
"""

from pathlib import Path

from . import findings, followups, question_flow, rules, timeline
from ..privacy import _DIGITS

JSON_PATH = Path(__file__).resolve().parents[3] / "frontend" / "src" / "lib" / "triage" / "rulepack.json"


def build() -> dict:
    sources, protocols, version = rules.load_pack()
    lexicon = {
        fid: [[lang, pat if lang == "en" else findings._indic_regex(pat).pattern] for lang, pats in langs.items() for pat in pats]
        for fid, langs in findings.LEXICON.items()
    }
    return {
        "note": "Generated by backend/scripts/build_rulepack.py from backend/app/triage; do not edit by hand.",
        "version": version,
        "sources": {k: v["short"] for k, v in sources.items()},
        "protocols": [
            {"key": p.key, "name": p.name, "applies": p.applies,
             "rules": [{"id": r.id, "description": r.description, "urgency": r.urgency, "when": r.when, "source": r.source,
                        "non_downgradable": r.non_downgradable, "review_by": r.review_by} for r in p.rules]}
            for p in protocols
        ],
        "findings": {k: list(v) for k, v in findings.FINDINGS.items()},
        "lexicon": lexicon,
        "tiles": findings.TILES,
        "answers": [list(a) for a in question_flow.answers_table()],
        "staff_answers": followups.ANSWER_FINDINGS,
        "implies": [list(x) for x in findings.IMPLIES],
        "negation": {
            "pre": findings.NEGATION_PRE.pattern,
            "post_en": findings.NEGATION_POST_EN.pattern,
            "post_indic": [findings._loose(n) for n in findings.NEGATION_POST_INDIC],
            "clause_split": findings.CLAUSE_SPLIT.pattern,
        },
        "loose": {"drop": ["୍ୱ", "୍ଵ"], "map": {chr(k): v or "" for k, v in findings._LOOSE.items()}},
        "vitals": list(rules.VITALS),
        "vital_label": rules.VITAL_LABEL,
        "unit": rules.UNIT,
        "exposure_label": rules.EXPOSURE_LABEL,
        "required_adult": list(rules.REQUIRED_ADULT),
        "required_child": list(rules.REQUIRED_CHILD),
        "duration_hours": [[p, list(r)] for p, r in rules.DURATION_HOURS],
        "duration_number": rules.DURATION_NUMBER,
        "onset": {
            "explicit": timeline.EXPLICIT.pattern,
            "relative": [list(x) for x in timeline.RELATIVE],
            "num": timeline.NUM,
            "unit_days": timeline.UNIT_DAYS,
            "not_before": timeline.NOT_ONSET_BEFORE,
            "not_after": timeline.NOT_ONSET_AFTER,
            "digits": {chr(k): v for k, v in _DIGITS.items()},
        },
    }
